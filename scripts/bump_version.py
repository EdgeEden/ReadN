#!/usr/bin/env python3
"""
Automated Version Management for ReadN.
Increments patch version by default, or sets specific version.

Usage:
    python scripts/bump_version.py            # Bumps patch: 1.1.0 -> 1.1.1
    python scripts/bump_version.py --patch    # Bumps patch: 1.1.0 -> 1.1.1
    python scripts/bump_version.py --minor    # Bumps minor: 1.1.0 -> 1.2.0
    python scripts/bump_version.py --major    # Bumps major: 1.1.0 -> 2.0.0
    python scripts/bump_version.py --set 1.1.0 # Sets to explicit version
    python scripts/bump_version.py --get      # Prints current version
"""

import sys
import re
from pathlib import Path
from datetime import datetime

ROOT_DIR = Path(__file__).resolve().parent.parent
APP_VERSION_DART = ROOT_DIR / "frontend" / "lib" / "config" / "app_version.dart"
PUBSPEC_YAML = ROOT_DIR / "frontend" / "pubspec.yaml"
BACKEND_MAIN = ROOT_DIR / "backend" / "app" / "main.py"
BACKEND_CONFIG = ROOT_DIR / "backend" / "app" / "config.py"
WEB_VERSION_JSON = ROOT_DIR / "frontend" / "web" / "version.json"


def read_current_version() -> tuple[str, int]:
    """Returns (version_str, build_number)"""
    if APP_VERSION_DART.exists():
        content = APP_VERSION_DART.read_text(encoding="utf-8")
        ver_match = re.search(r"current\s*=\s*'([^']+)'", content)
        bld_match = re.search(r"buildNumber\s*=\s*(\d+)", content)
        if ver_match:
            ver = ver_match.group(1)
            bld = int(bld_match.group(1)) if bld_match else 1
            return ver, bld

    if PUBSPEC_YAML.exists():
        content = PUBSPEC_YAML.read_text(encoding="utf-8")
        match = re.search(r"^version:\s*([0-9]+\.[0-9]+\.[0-9]+)(?:\+([0-9]+))?", content, re.MULTILINE)
        if match:
            ver = match.group(1)
            bld = int(match.group(2)) if match.group(2) else 1
            return ver, bld

    return "1.1.0", 1


def parse_semver(ver: str) -> tuple[int, int, int]:
    parts = ver.split(".")
    major = int(parts[0]) if len(parts) > 0 else 1
    minor = int(parts[1]) if len(parts) > 1 else 0
    patch = int(parts[2]) if len(parts) > 2 else 0
    return major, minor, patch


def write_version(new_ver: str, new_build: int):
    today = datetime.now().strftime("%Y-%m-%d")

    # 1. Update frontend/lib/config/app_version.dart
    APP_VERSION_DART.parent.mkdir(parents=True, exist_ok=True)
    dart_code = f"""// This file is automatically generated by scripts/bump_version.py.
// Do not edit this file directly.

class AppVersion {{
  static const String current = '{new_ver}';
  static const int buildNumber = {new_build};
  static const String releaseDate = '{today}';

  static String get displayVersion => 'v$current';
  static String get fullDisplay => 'ReadN v$current ($buildNumber)';
}}
"""
    APP_VERSION_DART.write_text(dart_code, encoding="utf-8")

    # 2. Update frontend/pubspec.yaml
    if PUBSPEC_YAML.exists():
        content = PUBSPEC_YAML.read_text(encoding="utf-8")
        updated = re.sub(
            r"^version:\s*.*$",
            f"version: {new_ver}+{new_build}",
            content,
            flags=re.MULTILINE
        )
        PUBSPEC_YAML.write_text(updated, encoding="utf-8")

    # 3. Update backend/app/main.py
    if BACKEND_MAIN.exists():
        content = BACKEND_MAIN.read_text(encoding="utf-8")
        updated = re.sub(
            r'version="[^"]+"',
            f'version="{new_ver}"',
            content
        )
        BACKEND_MAIN.write_text(updated, encoding="utf-8")

    # 4. Update backend/app/config.py if it contains APP_VERSION
    if BACKEND_CONFIG.exists():
        content = BACKEND_CONFIG.read_text(encoding="utf-8")
        if "APP_VERSION" in content:
            updated = re.sub(
                r'APP_VERSION\s*=\s*"[^"]+"',
                f'APP_VERSION = "{new_ver}"',
                content
            )
        else:
            updated = content + f'\nAPP_VERSION = "{new_ver}"\n'
        BACKEND_CONFIG.write_text(updated, encoding="utf-8")

    # 5. Update web/version.json if it exists
    if WEB_VERSION_JSON.exists():
        import json
        try:
            data = json.loads(WEB_VERSION_JSON.read_text(encoding="utf-8"))
            data["app_name"] = "frontend"
            data["version"] = new_ver
            data["build_number"] = str(new_build)
            data["package_name"] = "frontend"
            WEB_VERSION_JSON.write_text(json.dumps(data, indent=2), encoding="utf-8")
        except Exception:
            pass


def main():
    args = sys.argv[1:]
    current_ver, current_build = read_current_version()

    if "--get" in args:
        print(f"{current_ver}+{current_build}")
        return

    target_ver = None
    target_build = current_build + 1

    if "--set" in args:
        idx = args.index("--set")
        if idx + 1 < len(args):
            target_ver = args[idx + 1]
            if "+" in target_ver:
                target_ver, bld_str = target_ver.split("+", 1)
                try:
                    target_build = int(bld_str)
                except ValueError:
                    pass
        else:
            print("Error: --set requires a version argument (e.g. 1.1.0)", file=sys.stderr)
            sys.exit(1)
    else:
        major, minor, patch = parse_semver(current_ver)
        if "--major" in args:
            target_ver = f"{major + 1}.0.0"
        elif "--minor" in args:
            target_ver = f"{major}.{minor + 1}.0"
        else:
            # Default or --patch: increment the last item (patch)
            target_ver = f"{major}.{minor}.{patch + 1}"

    write_version(target_ver, target_build)
    print(f"[Auto-Version] Version updated: {current_ver} -> {target_ver} (build {target_build})")


if __name__ == "__main__":
    main()

